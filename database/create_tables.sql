-- CREARE TABELE - SISTEM GESTIUNE CLINICA MEDICALA (PR_)


CREATE TABLE PR_ROLURI_PERSONAL (
    ID_ROL       NUMBER(5)     NOT NULL,
    DENUMIRE_ROL VARCHAR2(50)  NOT NULL
);

CREATE TABLE PR_SPECIALITATI (
    ID_SPECIALITATE NUMBER(5)    NOT NULL,
    DENUMIRE        VARCHAR2(80) NOT NULL
);

CREATE TABLE PR_PACIENTI (
    ID_PACIENT      NUMBER(10)   NOT NULL,
    CNP             VARCHAR2(13) NOT NULL,
    NUME            VARCHAR2(50) NOT NULL,
    PRENUME         VARCHAR2(50) NOT NULL,
    DATA_NASTERE    DATE         NOT NULL,
    NIVEL_ASIGURARE VARCHAR2(30) NOT NULL
);

CREATE TABLE PR_PERSONAL_CLINICA (
    ID_PERSONAL     NUMBER(10)    NOT NULL,
    NUME            VARCHAR2(50)  NOT NULL,
    PRENUME         VARCHAR2(50)  NOT NULL,
    DATA_ANGAJARE   DATE          NOT NULL,
    SALARIU         NUMBER(10, 2) NOT NULL,
    ID_ROL          NUMBER(5)     NOT NULL,
    ID_SPECIALITATE NUMBER(5),
    ID_MANAGER      NUMBER(10)
);

CREATE TABLE PR_SERVICII_MEDICALE (
    ID_SERVICIU       NUMBER(10)    NOT NULL,
    DENUMIRE_SERVICIU VARCHAR2(100) NOT NULL,
    CATEGORIE         VARCHAR2(50)  NOT NULL,
    PRET_LISTA        NUMBER(10, 2) NOT NULL
);

CREATE TABLE PR_MEDICAMENTE (
    ID_MEDICAMENT       NUMBER(10)    NOT NULL,
    DENUMIRE_COMERCIALA VARCHAR2(100) NOT NULL,
    SUBSTANTA_ACTIVA    VARCHAR2(100) NOT NULL,
    AMBALAJ             VARCHAR2(50)  NOT NULL,
    PRET_REFERINTA      NUMBER(10, 2) NOT NULL
);

CREATE TABLE PR_PROGRAMARI (
    ID_PROGRAMARE    NUMBER(10)   NOT NULL,
    DATA_ORA         TIMESTAMP    NOT NULL,
    STARE_PROGRAMARE VARCHAR2(20) NOT NULL,
    ID_PACIENT       NUMBER(10)   NOT NULL,
    ID_PERSONAL      NUMBER(10)   NOT NULL,
    ID_SERVICIU      NUMBER(10)   NOT NULL
);

CREATE TABLE PR_FISA_CONSULTATIE (
    ID_PROGRAMARE NUMBER(10)    NOT NULL,
    DIAGNOSTIC    VARCHAR2(250) NOT NULL,
    RECOMANDARI   VARCHAR2(500)
);

CREATE TABLE PR_RETETE (
    ID_RETETA             NUMBER(10)   NOT NULL,
    ID_PROGRAMARE         NUMBER(10)   NOT NULL,
    DATA_EMITERE          DATE         NOT NULL,
    PERIOADA_VALABILITATE NUMBER(4)    NOT NULL,
    COD_REFERINTA         VARCHAR2(30) NOT NULL
);

CREATE TABLE PR_DETALII_RETETA (
    ID_RETETA     NUMBER(10)    NOT NULL,
    ID_MEDICAMENT NUMBER(10)    NOT NULL,
    CANTITATE     NUMBER(5)     NOT NULL,
    COMPENSARE    NUMBER(10, 2) DEFAULT 0 NOT NULL,
    DOZAJ         VARCHAR2(150) NOT NULL
);