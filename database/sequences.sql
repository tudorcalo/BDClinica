-- SECVENTE, INDECSI SI OBIECTE AUXILIARE


-- Secventa pentru servicii medicale noi 
CREATE SEQUENCE SEQ_ID_SERVICIU_NOU
    START WITH 1000
    INCREMENT BY 10
    NOCACHE
    NOCYCLE;

-- Secvente suplimentare pentru inserari viitoare
CREATE SEQUENCE SEQ_PR_PACIENTI
    START WITH 31
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_PR_PROGRAMARI
    START WITH 26
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_PR_RETETE
    START WITH 13
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Indecsi
CREATE UNIQUE INDEX IDX_PR_MEDICAMENTE_PRODUS
    ON PR_MEDICAMENTE (DENUMIRE_COMERCIALA, SUBSTANTA_ACTIVA);

CREATE INDEX IDX_PR_PROGRAMARI_STARE
    ON PR_PROGRAMARI (STARE_PROGRAMARE);