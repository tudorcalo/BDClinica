-- ADVANCED QUERIES

-- 1. [GROUP BY / HAVING] Medicii cu cel putin 3 programari efectuate
SELECT
    ang.NUME,
    ang.PRENUME,
    COUNT(pr.ID_PROGRAMARE) AS Numar_Programari_Efectuate
FROM PR_PERSONAL_CLINICA ang
JOIN PR_PROGRAMARI pr ON pr.ID_PERSONAL = ang.ID_PERSONAL
WHERE pr.STARE_PROGRAMARE = 'Efectuata'
GROUP BY ang.ID_PERSONAL, ang.NUME, ang.PRENUME
HAVING COUNT(pr.ID_PROGRAMARE) >= 3
ORDER BY Numar_Programari_Efectuate DESC;

-- 2. [GROUP BY] Suma totala a compensarilor pe pacient
SELECT
    P.NUME || ' ' || P.PRENUME AS Nume_Pacient_Complet,
    SUM(DR.COMPENSARE) AS Suma_Totala_Compensata
FROM PR_PACIENTI P
JOIN PR_PROGRAMARI PRG    ON P.ID_PACIENT      = PRG.ID_PACIENT
JOIN PR_RETETE RT         ON PRG.ID_PROGRAMARE = RT.ID_PROGRAMARE
JOIN PR_DETALII_RETETA DR ON RT.ID_RETETA      = DR.ID_RETETA
GROUP BY P.ID_PACIENT, P.NUME, P.PRENUME
ORDER BY Suma_Totala_Compensata DESC;

-- 3. [GROUP BY] Varsta medie a pacientilor pe specialitate
SELECT
    sp.DENUMIRE AS Specialitate,
    TRUNC(AVG(TRUNC(MONTHS_BETWEEN(SYSDATE, p.DATA_NASTERE) / 12))) AS Varsta_Medie_Pacienti
FROM PR_PACIENTI p
JOIN PR_PROGRAMARI pr        ON p.ID_PACIENT        = pr.ID_PACIENT
JOIN PR_PERSONAL_CLINICA ang ON pr.ID_PERSONAL      = ang.ID_PERSONAL
JOIN PR_SPECIALITATI sp      ON ang.ID_SPECIALITATE = sp.ID_SPECIALITATE
GROUP BY sp.ID_SPECIALITATE, sp.DENUMIRE
ORDER BY Varsta_Medie_Pacienti DESC;

-- 4. [GROUP BY / HAVING] Categorii de servicii cu pret mediu peste 100 RON
SELECT
    CATEGORIE,
    TRUNC(AVG(PRET_LISTA), 2) AS Pret_Mediu_Categorie
FROM PR_SERVICII_MEDICALE
GROUP BY CATEGORIE
HAVING AVG(PRET_LISTA) > 100
ORDER BY Pret_Mediu_Categorie DESC;

-- 5. [SUBCERERE CORELATA] Medici cu salariu sub media specialitatii + afisarea mediei
SELECT
    PC.NUME || ' ' || PC.PRENUME AS Nume_Complet_Medic,
    S.DENUMIRE AS Specialitate,
    PC.SALARIU AS Salariu_Medic,
    (
        SELECT TRUNC(AVG(PC2.SALARIU), 2)
        FROM PR_PERSONAL_CLINICA PC2
        WHERE PC2.ID_SPECIALITATE = PC.ID_SPECIALITATE
    ) AS Salariu_Mediu_Specialitate
FROM PR_PERSONAL_CLINICA PC
JOIN PR_SPECIALITATI S ON PC.ID_SPECIALITATE = S.ID_SPECIALITATE
WHERE PC.SALARIU < (
    SELECT AVG(PC3.SALARIU)
    FROM PR_PERSONAL_CLINICA PC3
    WHERE PC3.ID_SPECIALITATE = PC.ID_SPECIALITATE
)
ORDER BY S.DENUMIRE, PC.SALARIU DESC;

-- 6. [WINDOW FUNCTION] Cel mai scump serviciu din fiecare categorie
SELECT DENUMIRE_SERVICIU, CATEGORIE, PRET_LISTA
FROM (
    SELECT
        DENUMIRE_SERVICIU,
        CATEGORIE,
        PRET_LISTA,
        ROW_NUMBER() OVER (PARTITION BY CATEGORIE ORDER BY PRET_LISTA DESC) AS RN
    FROM PR_SERVICII_MEDICALE
)
WHERE RN = 1;

-- 7. [DECODE] Clasificarea personalului pe transe salariale
SELECT
    NUME,
    PRENUME,
    SALARIU,
    DECODE(
        SIGN(SALARIU - 10000),
        1, 'Salariu Mare',
        DECODE(SIGN(SALARIU - 5000), 1, 'Salariu Mediu', 'Salariu Mic')
    ) AS Clasa_Salariu
FROM PR_PERSONAL_CLINICA;

-- 8. [CASE] Status detaliat pentru programarile efectuate
SELECT
    PR.ID_PROGRAMARE,
    PR.DATA_ORA,
    CASE
        WHEN RT.ID_RETETA IS NOT NULL     THEN 'Vizita cu Prescriptie Medicala'
        WHEN FC.ID_PROGRAMARE IS NOT NULL THEN 'Vizita Fara Prescriptie (doar Fisa)'
        ELSE 'Fara Fisa/Reteta'
    END AS Status_Vizita_Final
FROM PR_PROGRAMARI PR
JOIN PR_FISA_CONSULTATIE FC ON PR.ID_PROGRAMARE = FC.ID_PROGRAMARE
LEFT JOIN PR_RETETE RT      ON PR.ID_PROGRAMARE = RT.ID_PROGRAMARE
WHERE PR.STARE_PROGRAMARE = 'Efectuată';

-- 9. [UNION] Lista combinata pacienti + personal
SELECT NUME, PRENUME, 'Pacient'  AS Tip_Persoana FROM PR_PACIENTI
UNION
SELECT NUME, PRENUME, 'Personal' AS Tip_Persoana FROM PR_PERSONAL_CLINICA
ORDER BY 3, 1;

-- 10. [MINUS] Medici care au emis retete, dar nu au efectuat ecografie abdominala (301)
SELECT PRG.ID_PERSONAL
FROM PR_PROGRAMARI PRG
JOIN PR_RETETE RT ON PRG.ID_PROGRAMARE = RT.ID_PROGRAMARE
MINUS
SELECT ID_PERSONAL
FROM PR_PROGRAMARI
WHERE ID_SERVICIU = 301;

-- 11. [INTERSECT] Pacienti care au avut atat Analize, cat si Imagistica
SELECT PRG.ID_PACIENT
FROM PR_PROGRAMARI PRG
JOIN PR_SERVICII_MEDICALE SM ON PRG.ID_SERVICIU = SM.ID_SERVICIU
WHERE SM.CATEGORIE = 'Analize'
INTERSECT
SELECT PRG.ID_PACIENT
FROM PR_PROGRAMARI PRG
JOIN PR_SERVICII_MEDICALE SM ON PRG.ID_SERVICIU = SM.ID_SERVICIU
WHERE SM.CATEGORIE = 'Imagistica';

-- 12. [VIEW] Tabel virtual pentru pacienti cu asigurare prioritara
CREATE OR REPLACE VIEW VW_PACIENTI_COMPLETA AS
SELECT
    CNP,
    NUME || ' ' || PRENUME AS Nume_Complet,
    NIVEL_ASIGURARE
FROM PR_PACIENTI
WHERE NIVEL_ASIGURARE IN ('Privat Gold', 'CAS Prioritar');

SELECT * FROM VW_PACIENTI_COMPLETA;