SET PERIOADA_VALABILITATE = PERIOADA_VALABILITATE + 30
WHERE ID_RETETA = 3;

COMMIT;

-- 2. Programari efectuate in Ianuarie 2025 cu detalii pacient, medic si serviciu
SELECT
    P.NUME || ' ' || P.PRENUME AS Pacient,
    M.NUME || ' ' || M.PRENUME AS Medic,
    TO_CHAR(PR.DATA_ORA, 'DD-MON-YYYY HH24:MI') AS Data_Programare,
    S.DENUMIRE_SERVICIU
FROM PR_PROGRAMARI PR
JOIN PR_PACIENTI P          ON PR.ID_PACIENT  = P.ID_PACIENT
JOIN PR_PERSONAL_CLINICA M  ON PR.ID_PERSONAL = M.ID_PERSONAL
JOIN PR_SERVICII_MEDICALE S ON PR.ID_SERVICIU = S.ID_SERVICIU
WHERE PR.STARE_PROGRAMARE = 'Efectuată'
  AND EXTRACT(MONTH FROM PR.DATA_ORA) = 1
  AND EXTRACT(YEAR FROM PR.DATA_ORA)  = 2025;

-- 3. Medicamente prescrise pentru diagnosticul 'Bronșită acută'
SELECT
    MD.DENUMIRE_COMERCIALA,
    MD.SUBSTANTA_ACTIVA,
    DR.DOZAJ
FROM PR_FISA_CONSULTATIE FC
JOIN PR_RETETE RT         ON FC.ID_PROGRAMARE = RT.ID_PROGRAMARE
JOIN PR_DETALII_RETETA DR ON RT.ID_RETETA     = DR.ID_RETETA
JOIN PR_MEDICAMENTE MD    ON DR.ID_MEDICAMENT = MD.ID_MEDICAMENT
WHERE FC.DIAGNOSTIC = 'Bronșită acută';

-- 4. Servicii medicale neutilizate in nicio programare (LEFT JOIN)
SELECT
    S.DENUMIRE_SERVICIU
FROM PR_SERVICII_MEDICALE S
LEFT JOIN PR_PROGRAMARI PR ON S.ID_SERVICIU = PR.ID_SERVICIU
WHERE PR.ID_SERVICIU IS NULL;

-- 5. Numarul de programari pentru fiecare serviciu medical
SELECT
    SM.DENUMIRE_SERVICIU,
    SM.CATEGORIE,
    COUNT(PR.ID_PROGRAMARE) AS Numar_Programari
FROM PR_SERVICII_MEDICALE SM
LEFT JOIN PR_PROGRAMARI PR ON SM.ID_SERVICIU = PR.ID_SERVICIU
GROUP BY SM.ID_SERVICIU, SM.DENUMIRE_SERVICIU, SM.CATEGORIE
ORDER BY Numar_Programari DESC, SM.DENUMIRE_SERVICIU ASC;

-- 6. Pacienti cu medicamente compensate > 50 RON
SELECT DISTINCT
    P.NUME || ' ' || P.PRENUME AS Pacient
FROM PR_PACIENTI P
JOIN PR_PROGRAMARI PR     ON P.ID_PACIENT     = PR.ID_PACIENT
JOIN PR_RETETE RT         ON PR.ID_PROGRAMARE = RT.ID_PROGRAMARE
JOIN PR_DETALII_RETETA DR ON RT.ID_RETETA     = DR.ID_RETETA
WHERE DR.COMPENSARE > 50.00;