WHERE ID_SERVICIU = 101;

UPDATE PR_PROGRAMARI
SET STARE_PROGRAMARE = 'Efectuata'
WHERE ID_PROGRAMARE = 14;

UPDATE PR_PERSONAL_CLINICA
SET ID_SPECIALITATE = 2
WHERE ID_PERSONAL = 106;

UPDATE PR_PERSONAL_CLINICA
SET SALARIU = SALARIU * 1.05
WHERE ID_ROL = 30;

