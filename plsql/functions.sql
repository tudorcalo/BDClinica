CREATE OR REPLACE FUNCTION FN_VERIFICA_ASIGURARE(p_id_pacient NUMBER) RETURN VARCHAR2 IS
    v_nivel PR_PACIENTI.NIVEL_ASIGURARE%TYPE;
BEGIN
    SELECT NIVEL_ASIGURARE INTO v_nivel
    FROM PR_PACIENTI
    WHERE ID_PACIENT = p_id_pacient;

    IF v_nivel IS NULL THEN
        RETURN 'Neasigurat';
    END IF;
    RETURN v_nivel;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Pacient inexistent';
END;
/

CREATE OR REPLACE FUNCTION FN_TOTAL_PLATA_PACIENT(p_id_pacient NUMBER) RETURN NUMBER IS
    v_total NUMBER := 0;
    CURSOR c_prog IS
        SELECT s.PRET_LISTA
        FROM PR_PROGRAMARI p
        JOIN PR_SERVICII_MEDICALE s ON p.ID_SERVICIU = s.ID_SERVICIU
        WHERE p.ID_PACIENT = p_id_pacient AND p.STARE_PROGRAMARE = 'Finalizata';
BEGIN
    FOR r IN c_prog LOOP
        v_total := v_total + NVL(r.PRET_LISTA, 0);
    END LOOP;
    RETURN v_total;
END;
/

CREATE OR REPLACE FUNCTION FN_NR_PROGRAMARI_MEDIC(p_id_personal NUMBER) RETURN NUMBER IS
    v_exista NUMBER;
    v_nr     NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exista FROM PR_PERSONAL_CLINICA WHERE ID_PERSONAL = p_id_personal;
    IF v_exista = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Angajatul specificat nu exista.');
    END IF;

    SELECT COUNT(*) INTO v_nr FROM PR_PROGRAMARI WHERE ID_PERSONAL = p_id_personal;
    RETURN v_nr;
END;
/

CREATE OR REPLACE FUNCTION FN_VALOARE_RETETA(p_id_reteta NUMBER) RETURN NUMBER IS
    v_total NUMBER := 0;
    CURSOR c_detalii IS
        SELECT d.CANTITATE, d.COMPENSARE, m.PRET_REFERINTA
        FROM PR_DETALII_RETETA d
        JOIN PR_MEDICAMENTE m ON d.ID_MEDICAMENT = m.ID_MEDICAMENT
        WHERE d.ID_RETETA = p_id_reteta;
BEGIN
    FOR r IN c_detalii LOOP
        v_total := v_total + (r.CANTITATE * r.PRET_REFERINTA * (1 - NVL(r.COMPENSARE, 0) / 100));
    END LOOP;
    RETURN ROUND(v_total, 2);
END;
/

CREATE OR REPLACE FUNCTION FN_VECHIME_ANGAJAT(p_id_personal NUMBER) RETURN NUMBER IS
    v_data_ang DATE;
BEGIN
    SELECT DATA_ANGAJARE INTO v_data_ang
    FROM PR_PERSONAL_CLINICA
    WHERE ID_PERSONAL = p_id_personal;

    RETURN ROUND(MONTHS_BETWEEN(SYSDATE, v_data_ang) / 12, 1);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
END;
/

CREATE OR REPLACE FUNCTION FN_NR_ANGAJATI_SPECIALITATE(p_id_spec NUMBER) RETURN NUMBER IS
    v_nr NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_nr
    FROM PR_PERSONAL_CLINICA
    WHERE ID_SPECIALITATE = p_id_spec;

    RETURN v_nr;
END;
