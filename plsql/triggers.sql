CREATE OR REPLACE TRIGGER TRG_VALIDARE_SALARIU
BEFORE INSERT OR UPDATE ON PR_PERSONAL_CLINICA
FOR EACH ROW
DECLARE
    v_sal_min NUMBER;
BEGIN
    IF :NEW.ID_ROL IS NOT NULL THEN
        SELECT SALARIU_MIN INTO v_sal_min
        FROM PR_ROLURI_PERSONAL
        WHERE ID_ROL = :NEW.ID_ROL;

        IF :NEW.SALARIU < v_sal_min THEN
            RAISE_APPLICATION_ERROR(-20010, 'Salariul este sub minimul admis pentru acest rol.');
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_PROGRAMARE_VIITOR
BEFORE INSERT OR UPDATE ON PR_PROGRAMARI
FOR EACH ROW
BEGIN
    IF :NEW.DATA_ORA < SYSDATE THEN
        RAISE_APPLICATION_ERROR(-20011, 'Nu se pot inregistra programari in trecut.');
    END IF;

    IF :NEW.STARE_PROGRAMARE NOT IN ('Programata', 'Finalizata', 'Anulata') THEN
        :NEW.STARE_PROGRAMARE := 'Programata';
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_VALIDARE_RETETA
BEFORE INSERT OR UPDATE ON PR_DETALII_RETETA
FOR EACH ROW
BEGIN
    IF :NEW.COMPENSARE < 0 OR :NEW.COMPENSARE > 100 THEN
        RAISE_APPLICATION_ERROR(-20012, 'Procentul de compensare trebuie sa fie intre 0 si 100.');
    END IF;

    IF :NEW.CANTITATE <= 0 THEN
        :NEW.CANTITATE := 1;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_VERIFICA_PRET_SERVICIU
BEFORE INSERT OR UPDATE ON PR_SERVICII_MEDICALE
FOR EACH ROW
BEGIN
    IF :NEW.PRET_LISTA <= 0 THEN
        RAISE_APPLICATION_ERROR(-20013, 'Pretul serviciului medical trebuie sa fie mai mare decat 0.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_VALIDARE_PACIENT
BEFORE INSERT OR UPDATE ON PR_PACIENTI
FOR EACH ROW
BEGIN
    IF LENGTH(:NEW.CNP) != 13 THEN
        RAISE_APPLICATION_ERROR(-20014, 'CNP-ul trebuie sa contina exact 13 caractere.');
    END IF;

    IF :NEW.EMAIL IS NOT NULL AND INSTR(:NEW.EMAIL, '@') = 0 THEN
        RAISE_APPLICATION_ERROR(-20015, 'Adresa de email introdusa nu este valida.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_PROTECTIE_STERGERE_ROL
BEFORE DELETE ON PR_ROLURI_PERSONAL
FOR EACH ROW
DECLARE
    v_nr_angajati NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_nr_angajati
    FROM PR_PERSONAL_CLINICA
    WHERE ID_ROL = :OLD.ID_ROL;

    IF v_nr_angajati > 0 THEN
        RAISE_APPLICATION_ERROR(-20016, 'Nu se poate sterge un rol care are angajati asignati.');
    END IF;
END;
/